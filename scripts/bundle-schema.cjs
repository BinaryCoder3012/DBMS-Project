#!/usr/bin/env node
/**
 * Writes the two derived SQL files, so they cannot drift from their sources:
 *
 *   schema/08_queries.sql   Q1 to Q6, from server/queries.js
 *   unigrant_schema.sql     schema/01 to 07 joined into a one-step install
 *
 * Run from the repository root:  npm run db:bundle
 */

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const queries = require(path.join(root, "server", "queries.js"));

const rule = "-- ============================================================";
const out = [
  rule,
  "--  UniGrant — Analytical Queries Q1 to Q6",
  "--  Owner: Arnav Gupta",
  "--  Generated from server/queries.js by npm run db:bundle",
  rule,
  "",
  "USE unigrant;",
  "",
];

for (const q of queries) {
  out.push(`-- ${q.id}: ${q.title}`, `-- Concept: ${q.concept}`, `-- ${q.purpose}`);
  if (q.params) {
    out.push(`SET @term = '${q.params[0]}';`);
    out.push(q.sql.replaceAll("?", "@term") + ";", "");
  } else {
    out.push(q.sql + ";", "");
  }
}
fs.writeFileSync(path.join(root, "schema", "08_queries.sql"), out.join("\n"));

const files = fs.readdirSync(path.join(root, "schema"))
  .filter(f => /^0[1-7]_.*\.sql$/.test(f))
  .sort();

const bundle = [
  rule,
  "--  UniGrant — complete install (generated by npm run db:bundle)",
  "--  Usage: mysql -u root -p < unigrant_schema.sql",
  "--  WARNING: drops and recreates the unigrant database.",
  rule,
  "",
  "DROP DATABASE IF EXISTS unigrant;",
  "",
];
for (const f of files) {
  bundle.push(fs.readFileSync(path.join(root, "schema", f), "utf8").replace(/\r\n/g, "\n"), "");
}
fs.writeFileSync(path.join(root, "unigrant_schema.sql"), bundle.join("\n"));
console.log(`wrote schema/08_queries.sql (${queries.length} queries) and unigrant_schema.sql (${files.length} files)`);
